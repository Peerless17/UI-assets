function filterResources() {
    const query = document.getElementById('searchInput').value.toLowerCase();
    const cat = document.getElementById('categoryFilter').value;
    const tag = document.getElementById('typeFilter').value;

    const filtered = allResources.filter(r => {
        const matchesSearch = r.title.toLowerCase().includes(query) || r.description.toLowerCase().includes(query);
        const matchesCat = cat === 'favorites' ? favorites.has(r.id) : (cat === 'all' || r.category === cat);
        const matchesTag = tag === 'all' || r.tags.includes(tag);
        return matchesSearch && matchesCat && matchesTag;
    });

    document.getElementById('resultsCount').textContent = `${filtered.length} Resources Found, Last updated 1/11/2026`;
    const group = cat === 'all' && !query && tag === 'all';
    renderResources(filtered, group);
    updateURL();
}

