function loadFavorites() {
    try {
        const stored = localStorage.getItem('resourceFavorites');
        if (stored) favorites = new Set(JSON.parse(stored));
    } catch (e) {
        console.error('Error loading favorites:', e);
    }
}

function saveFavorites() {
    try {
        localStorage.setItem('resourceFavorites', JSON.stringify([...favorites]));
    } catch (e) {
        console.error('Error saving favorites:', e);
    }
}

function toggleFavorite(resourceId, event) {
    if (event) {
        event.stopPropagation();
        event.preventDefault();
    }
    
    if (favorites.has(resourceId)) {
        favorites.delete(resourceId);
    } else {
        favorites.add(resourceId);
    }
    saveFavorites();
    filterResources();
}

function exportFavorites() {
    const data = { favorites: [...favorites], exportDate: new Date().toISOString() };
    const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `favorites-${new Date().toISOString().split('T')[0]}.json`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
}

function importFavorites() {
    const input = document.createElement('input');
    input.type = 'file';
    input.accept = 'application/json';
    input.onchange = e => {
        const file = e.target.files[0];
        if (!file) return;
        const reader = new FileReader();
        reader.onload = event => {
            try {
                const data = JSON.parse(event.target.result);
                if (data.favorites && Array.isArray(data.favorites)) {
                    favorites = new Set(data.favorites);
                    saveFavorites();
                    filterResources();
                    alert(`Imported ${data.favorites.length} favorites!`);
                } else {
                    alert('Invalid favorites file format');
                }
            } catch (error) {
                console.error('Import error:', error);
                alert('Error importing favorites file');
            }
        };
        reader.readAsText(file);
    };
    input.click();
}

