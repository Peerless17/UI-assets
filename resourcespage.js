function updateURL() {
    const params = new URLSearchParams();
    const search = document.getElementById('searchInput').value;
    const category = document.getElementById('categoryFilter').value;
    const tag = document.getElementById('typeFilter').value;

    if (search) params.set('search', search);
    if (category && category !== 'all') params.set('category', category);
    if (tag && tag !== 'all') params.set('tag', tag);

    const newURL = params.toString() ? `${location.pathname}?${params}` : location.pathname;
    history.replaceState({}, '', newURL);
}

function loadFromURL() {
    const params = new URLSearchParams(location.search);
    document.getElementById('searchInput').value = params.get('search') || '';
    document.getElementById('categoryFilter').value = params.get('category') || 'all';
    document.getElementById('typeFilter').value = params.get('tag') || 'all';
}

